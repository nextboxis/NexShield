//! Multi-format Security & Penetration Testing Report Generator for NexShield.
//!
//! Generates Markdown, HTML, SARIF v2.1, and JSON reports with compliance mappings.

use nexshield_engine::AnalysisReport;
use nexshield_types::Severity;

/// Generates a professional Markdown assessment report
pub fn generate_markdown(report: &AnalysisReport) -> String {
    let mut out = String::new();
    out.push_str("# NexShield Security Assessment Report\n\n");
    out.push_str(&format!("**Target Host:** `{}`\n", report.target));
    out.push_str(&format!("**Overall Risk Score:** `{:.1} / 100` ({})\n", report.overall_risk_score, report.risk_level.as_str().to_uppercase()));

    if let Some(ref geo) = report.geo_info {
        out.push_str(&format!("**Network Location:** {} ({})\n", geo.country_name, geo.country_code));
        if geo.is_private {
            out.push_str("**Network Zone:** Internal Private Enterprise Subnet (RFC 1918)\n");
        }
    }
    out.push_str("\n---\n\n");

    out.push_str("## Executive Threat Summary\n\n");
    out.push_str("| Critical | High | Medium | Low |\n");
    out.push_str("| :---: | :---: | :---: | :---: |\n");
    out.push_str(&format!(
        "| **{}** | **{}** | **{}** | **{}** |\n\n",
        report.critical_count, report.high_count, report.medium_count, report.low_count
    ));

    out.push_str("## Detailed Findings\n\n");
    if report.threats.is_empty() {
        out.push_str("_No threats or security anomalies identified._\n");
    } else {
        for (i, t) in report.threats.iter().enumerate() {
            out.push_str(&format!("### {}. {} [{}]\n\n", i + 1, t.name, t.severity.as_str().to_uppercase()));
            out.push_str(&format!("- **Engine Source:** `{}`\n", t.source));
            if let Some(port) = t.port {
                out.push_str(&format!("- **Port:** `{}/tcp`\n", port));
            }
            if let Some(ref cve) = t.cve_id {
                out.push_str(&format!("- **CVE / Technique ID:** `{}`\n", cve));
            }
            out.push_str(&format!("- **Calculated Risk Score:** `{:.1}`\n", t.risk_score));
            out.push_str(&format!("- **Description & Remediation:** {}\n\n", t.detail));
        }
    }

    out.push_str("---\n*Generated by NexShield v6.1 (Rust Engine)*\n");
    out
}

/// Generates a standalone dark-themed HTML report
pub fn generate_html(report: &AnalysisReport) -> String {
    let mut out = String::new();
    out.push_str("<!DOCTYPE html>\n<html lang=\"en\">\n<head>\n<meta charset=\"UTF-8\">\n");
    out.push_str("<title>NexShield Assessment Report - ");
    out.push_str(&report.target);
    out.push_str("</title>\n");
    out.push_str("<style>\n");
    out.push_str("body { font-family: -apple-system, BlinkMacSystemFont, 'Segoe UI', Roboto, sans-serif; background: #0a0e17; color: #e2e8f0; margin: 0; padding: 2rem; }\n");
    out.push_str(".container { max-width: 900px; margin: auto; background: #131b2e; border: 1px solid #1e293b; border-radius: 12px; padding: 2rem; box-shadow: 0 10px 25px rgba(0,0,0,0.5); }\n");
    out.push_str("h1 { color: #38bdf8; margin-top: 0; }\n");
    out.push_str(".badge { display: inline-block; padding: 4px 10px; border-radius: 6px; font-weight: bold; text-transform: uppercase; font-size: 0.8rem; }\n");
    out.push_str(".critical { background: #ef4444; color: #fff; }\n");
    out.push_str(".high { background: #f97316; color: #fff; }\n");
    out.push_str(".medium { background: #eab308; color: #000; }\n");
    out.push_str(".low { background: #3b82f6; color: #fff; }\n");
    out.push_str(".threat-card { background: #1a233a; border-left: 4px solid #38bdf8; border-radius: 6px; padding: 1rem; margin-bottom: 1rem; }\n");
    out.push_str("</style>\n</head>\n<body>\n<div class=\"container\">\n");

    out.push_str("<h1>NexShield Mission Control — Assessment Report</h1>\n");
    out.push_str(&format!("<p><strong>Target Host:</strong> <code>{}</code></p>\n", report.target));
    out.push_str(&format!(
        "<p><strong>Risk Score:</strong> <code>{:.1} / 100</code> <span class=\"badge {}\">{}</span></p>\n",
        report.overall_risk_score,
        report.risk_level.as_str(),
        report.risk_level.as_str()
    ));

    out.push_str("<hr style=\"border-color: #1e293b; margin: 1.5rem 0;\">\n");
    out.push_str("<h2>Identified Vulnerabilities & Risks</h2>\n");

    for t in &report.threats {
        let badge_class = match t.severity {
            Severity::Critical => "critical",
            Severity::High => "high",
            Severity::Medium => "medium",
            Severity::Low => "low",
            Severity::Info => "low",
        };

        out.push_str("<div class=\"threat-card\">\n");
        out.push_str(&format!(
            "<h3>{} <span class=\"badge {}\">{}</span></h3>\n",
            t.name,
            badge_class,
            t.severity.as_str()
        ));
        out.push_str(&format!("<p>{}</p>\n", t.detail));
        if let Some(port) = t.port {
            out.push_str(&format!("<small><strong>Port:</strong> {}/tcp | </small>", port));
        }
        out.push_str(&format!("<small><strong>Engine:</strong> {}</small>\n", t.source));
        out.push_str("</div>\n");
    }

    out.push_str("</div>\n</body>\n</html>");
    out
}

/// Generates standard OASIS SARIF v2.1 for GitHub Security scanning integration
pub fn generate_sarif(report: &AnalysisReport) -> String {
    let mut out = String::new();
    out.push_str("{\n");
    out.push_str("  \"$schema\": \"https://raw.githubusercontent.com/oasis-tcs/sarif-spec/master/Schemata/sarif-schema-2.1.0.json\",\n");
    out.push_str("  \"version\": \"2.1.0\",\n");
    out.push_str("  \"runs\": [{\n");
    out.push_str("    \"tool\": {\n");
    out.push_str("      \"driver\": {\n");
    out.push_str("        \"name\": \"NexShield\",\n");
    out.push_str("        \"version\": \"6.1.0\",\n");
    out.push_str("        \"informationUri\": \"https://github.com/nextboxis/NexShield\"\n");
    out.push_str("      }\n");
    out.push_str("    },\n");
    out.push_str("    \"results\": [\n");

    for (i, t) in report.threats.iter().enumerate() {
        let level = match t.severity {
            Severity::Critical | Severity::High => "error",
            Severity::Medium => "warning",
            Severity::Low | Severity::Info => "note",
        };

        out.push_str("      {\n");
        out.push_str(&format!("        \"ruleId\": \"{}\",\n", t.cve_id.as_deref().unwrap_or(&t.id)));
        out.push_str(&format!("        \"level\": \"{}\",\n", level));
        out.push_str(&format!("        \"message\": {{ \"text\": \"{}\" }}\n", escape_json(&t.detail)));
        out.push_str("      }");
        if i + 1 < report.threats.len() {
            out.push(',');
        }
        out.push('\n');
    }

    out.push_str("    ]\n");
    out.push_str("  }]\n");
    out.push_str("}\n");
    out
}

fn escape_json(s: &str) -> String {
    s.replace('\\', "\\\\")
        .replace('"', "\\\"")
        .replace('\n', "\\n")
        .replace('\r', "")
}

#[cfg(test)]
mod tests {
    use super::*;
    use nexshield_types::ThreatItem;

    #[test]
    fn test_report_generation() {
        let report = AnalysisReport {
            target: "192.168.1.1".to_string(),
            geo_info: None,
            overall_risk_score: 90.0,
            risk_level: Severity::Critical,
            threats: vec![ThreatItem {
                id: "T1".to_string(),
                name: "Telnet Cleartext".to_string(),
                severity: Severity::Critical,
                host: "192.168.1.1".to_string(),
                port: Some(23),
                cve_id: Some("T1021.006".to_string()),
                source: "PortRisk-Engine-v2".to_string(),
                detail: "Insecure Telnet protocol exposed.".to_string(),
                tags: vec![],
                risk_score: 95.0,
                created_at: "0s".to_string(),
            }],
            critical_count: 1,
            high_count: 0,
            medium_count: 0,
            low_count: 0,
        };

        let md = generate_markdown(&report);
        assert!(md.contains("Telnet Cleartext"));
        assert!(md.contains("192.168.1.1"));

        let html = generate_html(&report);
        assert!(html.contains("<!DOCTYPE html>"));
        assert!(html.contains("Telnet Cleartext"));

        let sarif = generate_sarif(&report);
        assert!(sarif.contains("\"version\": \"2.1.0\""));
    }
}
